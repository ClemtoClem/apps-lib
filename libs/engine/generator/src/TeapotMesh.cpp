TeapotMesh::TriangleGenerator::TriangleGenerator(const TeapotMesh& mesh) noexcept :
	m_mMesh{&mesh},
	m_mIndex{0},
	m_mPatchMesh{std::make_shared<BezierMesh<4, 4>>(teapotData[0], math::IVec2{mesh.m_mSegments, mesh.m_mSegments})},
	m_mTriangles{m_mPatchMesh->Triangles()}
{ }


bool TeapotMesh::TriangleGenerator::Done() const noexcept
{
	return m_mIndex == 32;
}


Triangle TeapotMesh::TriangleGenerator::Generate() const
{
	assert(!(Done()) && "générateur épuisé");

	Triangle triangle = m_mTriangles.Generate();

	const int base = m_mIndex * m_mMesh->m_mPatchVertexCount;

	triangle.vertices[0] += base;
	triangle.vertices[1] += base;
	triangle.vertices[2] += base;

	return triangle;
}


void TeapotMesh::TriangleGenerator::Next()
{
	assert(!(Done()) && "générateur épuisé");

	m_mTriangles.Next();

	if (m_mTriangles.Done()) {
		++m_mIndex;

		if (!Done()) {
			m_mPatchMesh = std::make_shared<BezierMesh<4, 4>>(
				teapotData[m_mIndex], math::IVec2{m_mMesh->m_mSegments, m_mMesh->m_mSegments}
			);

			m_mTriangles = m_mPatchMesh->Triangles();
		}
	}
}


